def select_pairs_for_qc(pairs: list[dict[str, Any]], low_sample: int, seed: int) -> list[dict[str, Any]]:
    high_medium = [p for p in pairs if p.get("rule_decision") in {"high", "medium"}]
    low = [p for p in pairs if p.get("rule_decision") == "low"]
    rng = random.Random(seed)
    rng.shuffle(low)
    return high_medium + low[:low_sample]


def chunks(items: list[Any], size: int) -> list[list[Any]]:
    return [items[i : i + size] for i in range(0, len(items), size)]


def run_pair_qc(args: argparse.Namespace, api_key: str | None, key_source: str) -> list[dict[str, Any]]:
    pair_path = args.out_dir / "helmet_miner_pairs.jsonl"
    out_path = args.out_dir / "reports/deepseek_qc_pairs.jsonl"
    pairs = select_pairs_for_qc(read_jsonl(pair_path), args.low_sample, args.seed)
    if args.max_pairs:
        pairs = pairs[: args.max_pairs]
    existing = {row["pair_id"]: row for row in read_jsonl(out_path)}
    todo = [pair for pair in pairs if args.force or pair["pair_id"] not in existing]
    done = len(existing)
    if not todo:
        return read_jsonl(out_path)
    if not api_key:
        for batch in chunks(todo, args.batch_size):
            rows = [fallback_pair_qc(pair, f"DeepSeek API unavailable ({key_source}); fallback rule QC used.") for pair in batch]
            append_jsonl(out_path, rows)
            done += len(rows)
            print(f"pair_qc done={done}/{len(pairs)}", flush=True)
        return read_jsonl(out_path)

    for batch in chunks(todo, args.batch_size):
        user = json.dumps(
            {
                "instruction": (
                    "Audit each item independently. Return a JSON object with key 'items'. "
                    "Each item must include pair_id, decision, risk_level, main_reason, "
                    "failure_modes, and recommended_use."
                ),
                "items": [compact_pair(pair) for pair in batch],
                "allowed_values": {
                    "decision": ["accept", "review", "reject"],
                    "risk_level": ["low", "medium", "high"],
                    "recommended_use": ["main_train", "weak_train", "val_review", "reject"],
                },
            },
            ensure_ascii=False,
        )
        try:
            raw = call_deepseek(
                api_key=api_key,
                base_url=args.base_url,
                model=args.pair_model,
                messages=[{"role": "system", "content": PAIR_SYSTEM}, {"role": "user", "content": user}],
                timeout=args.timeout,
                retries=args.retries,
                json_output=True,
            )
            assert isinstance(raw, dict)
            raw_items = raw.get("items")
            if not isinstance(raw_items, list):
                raise ValueError("pair batch response missing items list")
            by_id = {str(item.get("pair_id")): item for item in raw_items if isinstance(item, dict)}
            missing_ids = [pair["pair_id"] for pair in batch if pair["pair_id"] not in by_id]
            if missing_ids and args.strict_api_qc:
                missing_pairs = [pair for pair in batch if pair["pair_id"] not in by_id]
                for retry_batch in chunks(missing_pairs, max(1, args.strict_retry_batch_size)):
                    retry_user = json.dumps(
                        {
                            "instruction": (
                                "Audit each item independently. Return a JSON object with key 'items'. "
                                "Each item must include pair_id, decision, risk_level, main_reason, "
                                "failure_modes, and recommended_use."
                            ),
                            "items": [compact_pair(pair) for pair in retry_batch],
                            "allowed_values": {
                                "decision": ["accept", "review", "reject"],
                                "risk_level": ["low", "medium", "high"],
                                "recommended_use": ["main_train", "weak_train", "val_review", "reject"],
                            },
                        },
                        ensure_ascii=False,
                    )
                    retry_raw = call_deepseek(
                        api_key=api_key,
                        base_url=args.base_url,
                        model=args.pair_model,
                        messages=[{"role": "system", "content": PAIR_SYSTEM}, {"role": "user", "content": retry_user}],
                        timeout=args.timeout,
                        retries=args.retries,
                        json_output=True,
                    )
                    assert isinstance(retry_raw, dict)
                    retry_items = retry_raw.get("items")
                    if not isinstance(retry_items, list):
                        raise ValueError("pair retry response missing items list")
                    by_id.update({str(item.get("pair_id")): item for item in retry_items if isinstance(item, dict)})
                missing_ids = [pair["pair_id"] for pair in batch if pair["pair_id"] not in by_id]
                for _attempt in range(args.strict_single_id_retries):
                    if not missing_ids:
                        break
                    for pair in [pair for pair in batch if pair["pair_id"] in set(missing_ids)]:
                        single_user = json.dumps(
                            {
                                "instruction": (
                                    "Audit this single item. Return a JSON object with key 'items' containing exactly one item. "
                                    "The item must include pair_id, decision, risk_level, main_reason, failure_modes, and recommended_use."
                                ),
                                "items": [compact_pair(pair)],
                                "allowed_values": {
                                    "decision": ["accept", "review", "reject"],
                                    "risk_level": ["low", "medium", "high"],
                                    "recommended_use": ["main_train", "weak_train", "val_review", "reject"],
                                },
                            },
                            ensure_ascii=False,
                        )
                        single_raw = call_deepseek(
                            api_key=api_key,
                            base_url=args.base_url,
                            model=args.pair_model,
                            messages=[{"role": "system", "content": PAIR_SYSTEM}, {"role": "user", "content": single_user}],
                            timeout=args.timeout,
                            retries=args.retries,
                            json_output=True,
                        )
                        assert isinstance(single_raw, dict)
                        single_items = single_raw.get("items")
                        if isinstance(single_items, list):
                            by_id.update({str(item.get("pair_id")): item for item in single_items if isinstance(item, dict)})
                    missing_ids = [pair["pair_id"] for pair in batch if pair["pair_id"] not in by_id]
                if missing_ids:
                    raise ValueError(
                        f"pair batch response missed {len(missing_ids)} ids after strict retries; first missing ids: {missing_ids[:5]}"
                    )
            rows = [
                normalize_pair_qc(pair, by_id[pair["pair_id"]], True, args.pair_model)
                if pair["pair_id"] in by_id
                else fallback_pair_qc(pair, "DeepSeek batch response missed this pair; fallback rule QC used.")
                for pair in batch
            ]
        except Exception as exc:  # noqa: BLE001
            if args.strict_api_qc:
                raise RuntimeError(f"Strict pair QC failed before writing fallback rows: {exc}") from exc
            rows = [fallback_pair_qc(pair, f"DeepSeek batch error; fallback rule QC used: {str(exc)[:240]}") for pair in batch]
        append_jsonl(out_path, rows)
        done += len(rows)
        print(f"pair_qc done={done}/{len(pairs)}", flush=True)
    return read_jsonl(out_path)


