def fallback_pair_qc(pair: dict[str, Any], reason: str) -> dict[str, Any]:
    decision = "review"
    risk = "medium"
    failures: list[str] = []
    if pair.get("ambiguous_score_gap"):
        failures.append("ambiguous_pair_score_gap")
    if pair.get("ambiguous_multi_head_match"):
        failures.append("ambiguous_multi_head_match")
    if not pair.get("helmet_center_in_miner"):
        failures.append("helmet_center_not_in_miner_bbox")
    if pair.get("center_in_head_score", 0.0) < 0.7:
        failures.append("weak_head_region_relation")
    if pair.get("sam_quality", 0.0) < 0.45:
        failures.append("low_miner_mask_quality")
    if pair.get("rule_decision") == "high" and not failures:
        decision = "accept"
        risk = "low"
    elif pair.get("rule_decision") == "low" or len(failures) >= 2:
        decision = "reject"
        risk = "high"
    recommended = {
        "accept": "main_train" if pair.get("rule_decision") == "high" else "weak_train",
        "review": "val_review",
        "reject": "reject",
    }[decision]
    return {
        "pair_id": pair["pair_id"],
        "used_api_key": False,
        "model": "fallback_rules",
        "decision": decision,
        "risk_level": risk,
        "main_reason": reason,
        "failure_modes": failures,
        "recommended_use": recommended,
        "rule_decision": pair.get("rule_decision"),
        "pair_score": pair.get("pair_score"),
    }


def fallback_episode_qc(ep: dict[str, Any], reason: str) -> dict[str, Any]:
    r1, r2 = ep["rounds"]
    q2 = str(r2.get("query", "")).lower()
    requires_ref = any(token in q2 for token in ["previous", "prior", "reference", "refer", "selected"])
    valid = (
        r1.get("target_category") == "coal_miner"
        and r1.get("target_type") == "pseudo"
        and r2.get("target_category") == "mining_helmet"
        and r2.get("target_type") == "sam_mask_from_real_bbox"
        and requires_ref
    )
    return {
        "episode_id": ep["episode_id"],
        "used_api_key": False,
        "model": "fallback_rules",
        "valid_episode": bool(valid),
        "round2_requires_ref": bool(requires_ref),
        "has_target_leakage": False,
        "pseudo_real_labeling_clear": bool(r1.get("target_type") == "pseudo" and "sam" in str(r2.get("target_type"))),
        "query_quality": "good" if requires_ref else "weak",
        "decision": "keep" if valid else "review",
        "main_reason": reason,
    }


def normalize_pair_qc(pair: dict[str, Any], raw: dict[str, Any], used_api: bool, model: str) -> dict[str, Any]:
    decision = str(raw.get("decision", "review")).lower()
    if decision not in {"accept", "review", "reject"}:
        decision = "review"
    risk = str(raw.get("risk_level", "medium")).lower()
    if risk not in {"low", "medium", "high"}:
        risk = "medium"
    recommended = str(raw.get("recommended_use", "val_review"))
    if recommended not in {"main_train", "weak_train", "val_review", "reject"}:
        recommended = "val_review"
    failures = raw.get("failure_modes", [])
    if not isinstance(failures, list):
        failures = [str(failures)]
    return {
        "pair_id": pair["pair_id"],
        "used_api_key": used_api,
        "model": model,
        "decision": decision,
        "risk_level": risk,
        "main_reason": str(raw.get("main_reason", ""))[:600],
        "failure_modes": [str(x)[:120] for x in failures],
        "recommended_use": recommended,
        "rule_decision": pair.get("rule_decision"),
        "pair_score": pair.get("pair_score"),
    }


