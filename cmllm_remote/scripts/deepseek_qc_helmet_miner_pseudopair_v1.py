def read_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    if not path.exists():
        return rows
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def append_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)


def load_key(args: argparse.Namespace) -> tuple[str | None, str]:
    if args.no_api:
        return None, "disabled_by_no_api"
    if args.api_key_file:
        key_path = Path(args.api_key_file)
    elif os.environ.get("DEEPSEEK_API_KEY_FILE"):
        key_path = Path(os.environ["DEEPSEEK_API_KEY_FILE"])
    else:
        key_path = None
    if key_path and key_path.exists():
        key = key_path.read_text(encoding="utf-8").strip()
        if args.consume_api_key_file:
            try:
                key_path.unlink()
            except OSError:
                pass
        return key or None, f"file:{key_path}"
    key = os.environ.get("DEEPSEEK_API_KEY")
    return (key.strip() if key else None), "env:DEEPSEEK_API_KEY" if key else "missing"


def strip_code_fence(text: str) -> str:
    text = text.strip()
    if text.startswith("```"):
        lines = text.splitlines()
        if lines and lines[0].startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].startswith("```"):
            lines = lines[:-1]
        return "\n".join(lines).strip()
    return text


def parse_json_response(text: str) -> dict[str, Any]:
    raw = strip_code_fence(text)
    try:
        payload = json.loads(raw)
    except json.JSONDecodeError:
        start = raw.find("{")
        end = raw.rfind("}")
        if start < 0 or end <= start:
            raise
        payload = json.loads(raw[start : end + 1])
    if not isinstance(payload, dict):
        raise ValueError("DeepSeek response is not a JSON object")
    return payload


def call_deepseek(
    *,
    api_key: str,
    base_url: str,
    model: str,
    messages: list[dict[str, str]],
    timeout: int,
    retries: int,
    json_output: bool = True,
) -> dict[str, Any] | str:
    url = base_url.rstrip("/") + "/chat/completions"
    body: dict[str, Any] = {
        "model": model,
        "messages": messages,
        "temperature": 0.0,
    }
    if json_output:
        body["response_format"] = {"type": "json_object"}
    data = json.dumps(body, ensure_ascii=False).encode("utf-8")
    headers = {
        "Content-Type": "application/json",
        "Authorization": f"Bearer {api_key}",
    }
    last_error: Exception | None = None
    for attempt in range(retries + 1):
        req = urllib.request.Request(url, data=data, headers=headers, method="POST")
        try:
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                payload = json.loads(resp.read().decode("utf-8"))
            content = payload["choices"][0]["message"]["content"]
            return parse_json_response(content) if json_output else content
        except (urllib.error.URLError, urllib.error.HTTPError, TimeoutError, KeyError, json.JSONDecodeError, ValueError) as exc:
            last_error = exc
            if attempt >= retries:
                break
            time.sleep(min(20, 2 ** attempt))
    raise RuntimeError(f"DeepSeek call failed: {last_error}")


